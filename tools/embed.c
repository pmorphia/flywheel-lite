/* Build tool: writes a C file embedding Flywheel library module sources.
 * usage: embed OUTPUT.c name=path.fw ... */
#include <stdio.h>
#include <stdlib.h>
#include <string.h>

int main(int argc, char **argv) {
    if (argc < 2) {
        fprintf(stderr, "usage: embed OUTPUT.c name=path ...\n");
        return 2;
    }
    FILE *out = fopen(argv[1], "wb");
    if (!out) {
        perror(argv[1]);
        return 1;
    }
    fputs("/* Generated by tools/embed.c; do not edit. */\n#include <stddef.h>\n#include <string.h>\n\n", out);
    for (int i = 2; i < argc; i++) {
        const char *eq = strchr(argv[i], '=');
        if (!eq) {
            fprintf(stderr, "bad argument %s\n", argv[i]);
            return 2;
        }
        FILE *in = fopen(eq + 1, "rb");
        if (!in) {
            perror(eq + 1);
            return 1;
        }
        fprintf(out, "static const char src_%d[] = {", i);
        int c, n = 0;
        while ((c = fgetc(in)) != EOF)
            fprintf(out, "%s%d,", n++ % 24 ? "" : "\n", c);
        fputs("0};\n", out);
        fclose(in);
    }
    fputs("\nconst char *lib_embedded_module(const char *name) {\n", out);
    for (int i = 2; i < argc; i++) {
        const char *eq = strchr(argv[i], '=');
        fprintf(out, "    if (!strncmp(name, \"%.*s\", %d) && !name[%d])\n        return src_%d;\n",
                (int)(eq - argv[i]), argv[i], (int)(eq - argv[i]), (int)(eq - argv[i]), i);
    }
    fputs("    return NULL;\n}\n", out);
    fclose(out);
    return 0;
}
